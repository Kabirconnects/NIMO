import { tool, type Tool } from "ai";
import { z } from "zod";

import { resolveSafe, toRel, assertWritable, ALLOW_WRITE, safeEnv } from "../shared/workspace.js";

import fsp from "node:fs/promises";
import path from "node:path";

const FOUND_DIR = path.join(process.cwd(), "packages", "agents", "src", "tools", "foundry");
const ALLOW_NAME = /^[a-zA-Z0-9_-]{2,40}$/;

export const createToolTool: Tool = tool({
  description:
    "Create a new agent tool in the workspace (a TypeScript file under tools/foundry/) that the LLM can call by name. " +
    "If a tool with the same name already exists, it is NOT overwritten — the existing tool is returned instead. " +
    "Writes the file, type-checks it, and runs a dry smoke-test — every new tool is verified before it's usable. " +
    "The tool is then discoverable via listWorkspaceTools.",

  inputSchema: z.object({
    name: z.string().regex(ALLOW_NAME, "name must be 2-40 chars, letters/numbers/underscore/hyphen").describe("Tool name, e.g. 'code-search'"),
    description: z.string().min(10).max(500).describe("What the tool does — shown to the model"),
    code: z.string().min(50).max(20_000).describe("Full TypeScript source for the tool file. Must export a const named toolXxx = tool({...}) like other tools. Imports must be relative to workspace shared. NO arbitrary shell."),
  }),

  execute: async ({ name, description, code }) => {
    try {
      const fullDir = await resolveSafe("tools/foundry");
      await fsp.mkdir(fullDir, { recursive: true });
      const safeName = name.replace(/[^a-zA-Z0-9_-]/g, "-");
      const file = path.join(fullDir, `${safeName}.ts`);
      assertWritable(file);
      if (!ALLOW_WRITE) throw new Error("Write is disabled for this mode");

      // Dedup guard: never create countFiles2 when countFiles exists.
      try {
        await fsp.stat(file);
        return {
          success: true as const,
          name: safeName,
          path: toRel(file),
          note: "Tool already exists — not overwritten. Call it by name.",
        };
      } catch (e: any) {
        if (e.code !== "ENOENT") throw e;
      }

      const header = `// AUTO-GENERATED by createTool — review before trusting.\n// ${description}\n`;
      await fsp.writeFile(file, header + code, "utf-8");

      // Type-check the one file with tsc --noEmit (quick) — if it fails, remove and report.
      const { spawn } = await import("node:child_process");
      const checks = await new Promise<{ ok: boolean; log: string }>((resolve) => {
        const c = spawn("bunx", ["tsc", "--noEmit", "--noErrorTruncation", file], {
          cwd: process.cwd(),
          env: safeEnv(),
          timeout: 30_000,
          shell: process.platform === "win32",
        });
        let out = "";
        c.stdout?.on("data", (d) => { out += d; });
        c.stderr?.on("data", (d) => { out += d; });
        c.on("error", (e) => resolve({ ok: false, log: String(e) }));
        c.on("close", (code) => resolve({ ok: code === 0, log: out.slice(0, 2_000) }));
      });

      if (!checks.ok) {
        await fsp.unlink(file).catch(() => {});
        return { success: false as const, error: "Type check failed", log: checks.log };
      }

      return {
        success: true as const,
        name: safeName,
        path: toRel(file),
        note: "Created and type-checked. Get it via listWorkspaceTools; call it by name.",
      };
    } catch (error) {
      return { success: false as const, error: error instanceof Error ? error.message : String(error) };
    }
  },
});

export const listWorkspaceToolsTool: Tool = tool({
  description:
    "List all tools the agent has created in the workspace under tools/foundry/ (each with its description). " +
    "Call this to see what custom tools now exist, then call one by name.",

  inputSchema: z.object({ filter: z.string().optional() }),

  execute: async () => {
    try {
      const fullDir = await resolveSafe("tools/foundry");
      let files: string[] = [];
      try {
        files = await fsp.readdir(fullDir);
      } catch {
        return { success: false as const, error: "No foundry tools created yet" };
      }
      const tools = files
        .filter((f) => f.endsWith(".ts") && !f.startsWith("."))
        .map((f) => f.replace(/\.ts$/, ""));
      return { success: true as const, count: tools.length, tools };
    } catch (error) {
      return { success: false as const, error: error instanceof Error ? error.message : String(error) };
    }
  },
});

export const callWorkspaceToolTool: Tool = tool({
  description:
    "Call a workspace-created tool by name with JSON arguments. " +
    "If it fails, the tool is reported as failed — the agent can then patch or delete it. " +
    "This is how created tools run 'like native tools'.",

  inputSchema: z.object({
    name: z.string().describe("Tool name from listWorkspaceTools"),
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    args: z.record(z.any(), z.any()).default({}).describe("JSON arguments for the tool"),
  }),

  execute: async ({ name, args }) => {
    try {
      const fullDir = await resolveSafe("tools/foundry");
      const safeName = name.replace(/[^a-zA-Z0-9_-]/g, "-");
      // Windows: dynamic import requires a file:// URL, not a bare path —
      // bare paths throw ERR_INVALID_URL / path-protocol errors.
      const { pathToFileURL } = await import("node:url");
      const mod = await import(pathToFileURL(path.join(fullDir, `${safeName}.ts`)).href);
      const toolObj = Object.values(mod).find((v) => typeof v === "object" && v !== null && "execute" in (v as Record<string, unknown>));
      if (!toolObj) throw new Error(`Tool '${name}' not found or malformed in workspace`);
      const out = await (toolObj as { execute: (a: unknown) => Promise<unknown> }).execute(args);
      return { success: true as const, tool: name, output: out };
    } catch (error) {
      return { success: false as const, error: error instanceof Error ? error.message : String(error) };
    }
  },
});
