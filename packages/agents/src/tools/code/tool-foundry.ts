import { tool, type Tool } from "ai";
import { z } from "zod";

import {
  resolveSafe,
  toRel,
  assertWritable,
  atomicWrite,
  ROOT,
} from "../shared/workspace.js";
import { assertCanWrite } from "../shared/permissions.js";
import { runProcess } from "../shared/process.js";

import fsp from "node:fs/promises";
import path from "node:path";

const ALLOW_NAME = /^[a-zA-Z0-9_-]{2,40}$/;

async function exists(file: string): Promise<boolean> {
  try {
    await fsp.access(file);
    return true;
  } catch {
    return false;
  }
}

export const createToolTool: Tool = tool({
  description:
    "Create a reusable tool in the workspace (tools/foundry/<name>.ts) that can be listed and called later. " +
    "Never overwrites an existing tool - if the name exists, the existing tool is returned. " +
    "The file is written atomically and validated for the expected `tool({ execute })` shape; " +
    "when the workspace has a tsconfig, it is also type-checked. " +
    "Use this to capture a repeated operation as a proper tool instead of re-deriving it. " +
    "Requires write permission.",

  inputSchema: z.object({
    name: z.string().regex(ALLOW_NAME, "name must be 2-40 chars: letters, numbers, underscore, hyphen")
      .describe("Tool name, e.g. 'count-todos'"),
    description: z.string().min(10).max(500).describe("What the tool does - shown to the model"),
    code: z.string().min(50).max(50_000)
      .describe(
        "Full TypeScript source. Export a tool object created with tool({ description, inputSchema, execute }). " +
        "Imports must use relative paths inside the workspace; no child_process or network access.",
      ),
  }),

  execute: async ({ name, description, code }) => {
    try {
      assertCanWrite("createTool");

      const fullDir = await resolveSafe("tools/foundry");
      await fsp.mkdir(fullDir, { recursive: true });

      const safeName = name.replace(/[^a-zA-Z0-9_-]/g, "-");
      const file = path.join(fullDir, `${safeName}.ts`);
      assertWritable(file);

      if (await exists(file)) {
        return {
          success: true as const,
          name: safeName,
          path: toRel(file),
          created: false,
          note: "Tool already exists - not overwritten. Call it with callWorkspaceTool.",
        };
      }

      if (!/\btool\s*\(/.test(code) || !/\bexecute\b/.test(code)) {
        throw new Error("Code must create a tool object with an execute function (tool({ ... }))");
      }
      if (!/\bexport\b/.test(code)) {
        throw new Error("Code must export the tool (export const myTool = tool({ ... }))");
      }

      const header =
        `// AUTO-GENERATED by createTool - review before trusting.\n` +
        `// ${description.replace(/\r?\n/g, " ")}\n`;
      await atomicWrite(file, header + code);

      // Optional typecheck: only meaningful when the workspace is a TypeScript
      // project with its own tsconfig + dependencies.
      let typecheck: { ok: boolean; log?: string; skipped?: string } = {
        ok: true,
        skipped: "No tsconfig.json in the workspace root",
      };
      if (await exists(path.join(ROOT, "tsconfig.json"))) {
        const result = await runProcess({
          argv: ["bunx", "tsc", "--noEmit", "--noErrorTruncation", "--skipLibCheck", toRel(file)],
          cwd: ROOT,
          timeoutMs: 60_000,
          maxOutputBytes: 20_000,
        });
        typecheck = { ok: result.ok, log: result.ok ? undefined : (result.stdout + result.stderr).slice(0, 4_000) };
      }

      return {
        success: true as const,
        name: safeName,
        path: toRel(file),
        created: true,
        typecheck,
        note: typecheck.ok
          ? "Created. List it with listWorkspaceTools, then call it with callWorkspaceTool."
          : "Created but typecheck failed - call it to test, then patch or delete the file.",
      };
    } catch (error) {
      return {
        success: false as const,
        error: error instanceof Error ? error.message : String(error),
      };
    }
  },
});

export const listWorkspaceToolsTool: Tool = tool({
  description:
    "List tools previously created in the workspace under tools/foundry/, with their description and metadata. " +
    "Use this to discover reusable tools before writing a new one.",

  inputSchema: z.object({
    filter: z.string().max(100).optional().describe("Case-insensitive name/description filter"),
  }),

  execute: async ({ filter }) => {
    try {
      const fullDir = await resolveSafe("tools/foundry");
      const files = await fsp.readdir(fullDir).catch(() => [] as string[]);

      const needle = filter?.toLowerCase();
      const tools = [];
      for (const entry of files) {
        if (!entry.endsWith(".ts") || entry.startsWith(".")) continue;
        const full = path.join(fullDir, entry);
        if (!(await exists(full))) continue;

        const head = (await fsp.readFile(full, "utf-8").catch(() => ""))
          .split(/\r?\n/)
          .slice(0, 5)
          .join(" ");
        const description = head.match(/\/\/\s*(?:AUTO-GENERATED[^-]*-\s*)?(.+)/)?.[1]?.slice(0, 200);
        const stat = await fsp.stat(full).catch(() => null);

        const info = {
          name: entry.replace(/\.ts$/, ""),
          path: toRel(full),
          description,
          bytes: stat?.size,
          mtime: stat?.mtime.toISOString(),
        };

        if (
          needle &&
          !info.name.toLowerCase().includes(needle) &&
          !(description ?? "").toLowerCase().includes(needle)
        ) {
          continue;
        }
        tools.push(info);
      }

      tools.sort((a, b) => a.name.localeCompare(b.name));
      return {
        success: true as const,
        count: tools.length,
        tools,
        hint: tools.length === 0 ? "No foundry tools yet. Use createTool to add one." : undefined,
      };
    } catch (error) {
      return {
        success: false as const,
        error: error instanceof Error ? error.message : String(error),
      };
    }
  },
});

export const callWorkspaceToolTool: Tool = tool({
  description:
    "Call a workspace-created tool by name with JSON arguments. " +
    "The tool receives the same filesystem sandbox and permissions. " +
    "If it fails, the error is returned so the agent can patch the tool file.",

  inputSchema: z.object({
    name: z.string().regex(ALLOW_NAME).describe("Tool name from listWorkspaceTools"),
    args: z.record(z.string(), z.unknown()).default({})
      .describe("Arguments object passed to the tool's execute function"),
  }),

  execute: async ({ name, args }) => {
    try {
      const safeName = name.replace(/[^a-zA-Z0-9_-]/g, "-");
      const fullDir = await resolveSafe("tools/foundry");
      const file = path.join(fullDir, `${safeName}.ts`);

      if (!(await exists(file))) {
        throw new Error(
          `Tool '${safeName}' not found. Use listWorkspaceTools to see available tools.`,
        );
      }

      const { pathToFileURL } = await import("node:url");
      const mod = await import(pathToFileURL(file).href);
      const toolObj = Object.values(mod).find(
        (value) =>
          typeof value === "object" &&
          value !== null &&
          typeof (value as Record<string, unknown>).execute === "function",
      );

      if (!toolObj) throw new Error(`Tool '${safeName}' is malformed (no execute function)`);

      const output = await (toolObj as { execute: (input: unknown) => Promise<unknown> })
        .execute(args);

      return { success: true as const, tool: safeName, output };
    } catch (error) {
      return {
        success: false as const,
        error: error instanceof Error ? error.message : String(error),
      };
    }
  },
});
